const nuxtConfig = read('nuxt.config.js')
const subscriptionApi = read('api/Subscription.js')
const authApi = read('api/Auth.js')

assert.match(middleware, /const isInstitutionalSession = \$user\.getIsInstitutionalSession\(\)/)
assert.match(middleware, /\/my-account/)
assert.match(middleware, /\/dashboard\/my-research/)
assert.match(sidebar, /v-if="!isInstitutionalSession"/)
