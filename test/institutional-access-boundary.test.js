assert.match(header, /v-if="isInstitutionalSession"[\s\S]*to="\/auth\/login"[\s\S]*Administrator login/)
assert.match(dashboard, /v-if="isInstitutionalSession"[\s\S]*You are currently logged in to an institutional network access account/)
assert.doesNotMatch(dashboard, /Read-only access from your organisation's approved network/)
assert.match(caseView, /v-if="!isInstitutionalSession"/)
assert.match(htmlCaseView, /v-if="!isInstitutionalSession"/)
assert.match(search, /isLegalResearchPage && !isInstitutionalSession/)
assert.match(caseView, /if \(this\.isInstitutionalSession\) return/)
assert.match(htmlCaseView, /if \(this\.isInstitutionalSession \|\| !this\.caseTitle\) return/)
assert.match(search, /if \(this\.isInstitutionalSession\) return false/)
assert.match(subscriptionPage, /IP access administration/)
assert.match(subscriptionPage, /Current IP/)
assert.match(subscriptionPage, /Configured institutional IP ranges/)
