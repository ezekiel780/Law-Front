assert.match(ipAuthPlugin, /window\.addEventListener\('load', afterHydration, \{ once: true \}\)/)
assert.match(ipAuthPlugin, /window\.requestAnimationFrame/)
assert.match(ipAuthPlugin, /!\$user\.getIsInstitutionalSession\(\)/)
assert.match(ipAuthPlugin, /app\.router\.replace\('\/dashboard'\)/)
assert.match(nuxtConfig, /ip-auth\.client\.js/)
assert.doesNotMatch(defaultLayout, /middleware:\s*'ip-auth\.middleware'/)
assert.doesNotMatch(dictionaryLayout, /middleware:\s*'ip-auth\.middleware'/)

// Institutional readers never enter personal subscription/account routes or an
// upgrade flow for capabilities their institutional plan does not include.
assert.match(middleware, /path\.includes\('\/dashboard\/my-subscription'\)/)
