assert.match(userStore, /sessionMode: null/)
assert.match(userStore, /getSessionMode/)
assert.match(userService, /getSessionMode:/)
assert.match(
  userService,
  /getIsInstitutionalSession:\s*\(\)\s*=>\s*store\.getters\['user\/getSessionMode'\]\s*===\s*'institutional_reader'/
)
assert.match(persister, /sessionMode: user\.sessionMode \|\| null/)
assert.match(persister, /VALID_SESSION_MODES/)
assert.match(persister, /if \(user\.isLoggedIn && !VALID_SESSION_MODES\.has\(user\.sessionMode\)\)/)
assert.match(loginForm, /response\.data\.success\.session\?\.mode/)
assert.match(loginForm, /setSessionMode\(sessionMode\)/)
assert.match(ipAuthPlugin, /sessionMode !== 'institutional_reader'/)
