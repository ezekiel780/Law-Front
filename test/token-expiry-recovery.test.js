const assert = require('assert')
const fs = require('fs')
const path = require('path')

const root = path.resolve(__dirname, '..')
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')

const guard = read('plugins/auth-token-guard.client.js')
const autoLogout = read('components/utils/auto-logout.vue')
const middleware = read('middleware/auth.middleware.js')
const policy = read('services/auth/session-policy.js')
const nuxtConfig = read('nuxt.config.js')

assert.match(nuxtConfig, /auth-token-guard\.client\.js/)
assert.match(guard, /\$axios\.onRequest/)
assert.match(guard, /\$axios\.onError/)
assert.match(guard, /status \|\| 0\) !== 401/)
assert.match(guard, /refreshNodeTokenOnce/)
assert.match(guard, /_nwlrAuthRetry/)
assert.match(guard, /return \$axios\.request\(config\)/)
assert.match(guard, /getLaravelToken/)
assert.match(guard, /responseStatus\(error\) === 401/)
assert.match(guard, /responseStatus\(refreshError\) === 401/)
assert.doesNotMatch(guard, /catch \(error\) \{\s*await expireSession\(\)/)
assert.match(guard, /revoke: false/)
assert.match(guard, /redirectTo: \$user\.getIsInstitutionalSession\(\) \? '\/' : '\/auth\/login'/)
assert.match(policy, /SESSION_IDLE_TIMEOUT_MS = 8 \* 60 \* 60 \* 1000/)
assert.match(autoLogout, /hasIdleSessionExpired/)
assert.match(autoLogout, /window\.addEventListener\('focus', this\.checkSessionValidity\)/)
assert.match(autoLogout, /visibilitychange/)
assert.match(autoLogout, /Please sign in again/)
assert.match(autoLogout, /const laravelToken = this\.\$user\.getLaravelToken\(\)/)
assert.match(autoLogout, /getIsIpUser\(\) && laravelToken && !nodeToken/)
assert.match(autoLogout, /if \(status !== 401\) return/)
assert.match(autoLogout, /this\.isInstitutionalSession && \(status === 401 \|\| status === 403\)/)
assert.match(middleware, /await \$user\.logout\(\{ force: true, revoke: false \}\)/)

console.log('Token expiry, refresh, retry and forced re-authentication checks passed.')
