const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '..')
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')

const signup = read('components/landing/auth/signup-step-2.vue')
const signupSuccess = read('components/landing/auth/signup-successful.vue')
const changePassword = read('components/dashboard/my-account/change-password.vue')
const login = read('components/landing/auth/login-form.vue')
const resetNewPassword = read('components/landing/auth/reset-new-password-form.vue')
const authApi = read('api/Auth.js')

assert.match(signup, /nwlr_registration_verification_notice/)
assert.match(signupSuccess, /Registration successful/)
assert.match(signupSuccess, /verify your email address before signing in/i)
assert.match(changePassword, /await this\.\$user\.logout\(\{/)
assert.match(changePassword, /nwlr_password_changed_notice/)
assert.doesNotMatch(changePassword, /Password changed successfully!/) 
assert.match(login, /nwlr_password_changed_notice/)
assert.match(login, /Sign in again with your new password/)
assert.match(signup, /corporate_invitation_completion_required/)
assert.match(signup, /nwlr_corporate_invitation_notice/)
assert.match(signupSuccess, /Complete Your Corporate Invitation/)
assert.match(resetNewPassword, /Complete Your Account/)
assert.match(resetNewPassword, /First Name/)
assert.match(resetNewPassword, /Last Name/)
assert.match(resetNewPassword, /Phone Number/)
assert.match(authApi, /firstname: payload\.firstname/)
assert.match(authApi, /phone: payload\.phone/)

console.log('customer auth UX regression checks passed')
